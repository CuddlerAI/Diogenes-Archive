//! shipped-games.json → 内嵌目录源码片段生成器。
//!
//! 被两个构建脚本以 `#[path]` 挂载复用：客户端 build.rs 与
//! tools/catalog-validator/build.rs（后者经 `#[path]` 挂载客户端 catalog.rs，
//! 同样需要 OUT_DIR 里的生成文件才能在 dev-catalog 特性下编译）。
//! 只依赖 std + serde_json，不得引入 tauri_build 等任一方独有的构建依赖。

/// 从 `config/catalogs/shipped-games.json` 生成两份源码片段（docs/57 的断代口径：
/// 「哪些游戏进包」只登记在 manifest 一处，其余全部派生）：
///
/// * `embedded_dev_catalogs.rs` —— `dev-catalog` 构建内嵌的全部游戏目录。每条
///   `games[].catalogDir` 展开五件套 `include_bytes!`；目录里若存在
///   `depth-profile.json` / `camera-binding.json` 则一并内嵌，游戏无须任何
///   编译期登记即可获得深度载荷（此前只有 Fallout 4 有一条手写分支）。
/// * `embedded_dev_game_ids.rs` —— 全量 game_id 名单，唯一消费者是
///   window_tracker.rs 的 roster 守卫测试：运行时 roster 必须与 manifest 派生集
///   精确相等，多一个少一个都红（此前那里是另一份手抄名单）。
///
/// 生成物按 manifest 顺序输出，完全确定；manifest 与目录内容都在上面的
/// rerun-if-changed 监听范围内。这里的每个 panic 都是构建期的显式失败——
/// 宁可编译失败也不让一个登记了却不存在的目录静默缺席。
pub(crate) fn emit_generated_catalog_sources(config_dir: &std::path::Path) {
    let manifest_path = config_dir.join("catalogs/shipped-games.json");
    let manifest = std::fs::read_to_string(&manifest_path)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", manifest_path.display()));
    let manifest: serde_json::Value = serde_json::from_str(&manifest)
        .unwrap_or_else(|error| panic!("cannot parse {}: {error}", manifest_path.display()));
    let games = manifest["games"]
        .as_array()
        .expect("shipped-games.json must carry a games array");
    assert!(
        !games.is_empty(),
        "shipped-games.json lists no games; an empty dev catalog build is never intended"
    );

    let mut catalog_entries = String::new();
    let mut game_ids: Vec<String> = Vec::new();
    let mut seen_dirs = std::collections::HashSet::new();
    for game in games {
        let game_id = game["gameId"]
            .as_str()
            .expect("shipped-games.json entry is missing gameId");
        let catalog_dir = game["catalogDir"]
            .as_str()
            .unwrap_or_else(|| panic!("shipped game {game_id} is missing catalogDir"));
        // 两个值都会被原样插进生成的 Rust 源码，字符集校验同时挡住格式破坏与
        // 生成期注入；重复检测接住「两条登记指向同一目录/同一 id」的手滑（旧
        // PowerShell 矩阵对重复 cargoFeature 会 throw，这里是同级守卫）。
        for (label, value) in [("gameId", game_id), ("catalogDir", catalog_dir)] {
            assert!(
                value
                    .bytes()
                    .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-'),
                "shipped game {game_id} has a {label} outside [a-z0-9-]: {value}"
            );
        }
        assert!(
            !game_ids.iter().any(|seen| seen == game_id),
            "shipped-games.json lists gameId {game_id} twice"
        );
        assert!(
            seen_dirs.insert(catalog_dir.to_owned()),
            "shipped-games.json lists catalogDir {catalog_dir} twice"
        );
        let bundle_dir = config_dir.join("catalogs/dev").join(catalog_dir);
        for required in [
            "catalog.json",
            "device-profile.json",
            "recording-profile.json",
            "game-profile.json",
            "mapping.json",
        ] {
            assert!(
                bundle_dir.join(required).is_file(),
                "shipped game {game_id} is missing {required} under {}",
                bundle_dir.display()
            );
        }
        let embed = |file: &str| {
            format!(
                "include_bytes!(concat!(env!(\"DATAMINER_CONFIG_DIR\"), \"/catalogs/dev/{catalog_dir}/{file}\"))"
            )
        };
        let optional_payloads = |file: &str| {
            if bundle_dir.join(file).is_file() {
                format!("&[{}]", embed(file))
            } else {
                "&[]".to_owned()
            }
        };
        catalog_entries.push_str(&format!(
            "        CatalogSources {{\n\
             \x20           manifest: {manifest},\n\
             \x20           devices: &[{device}],\n\
             \x20           recordings: &[{recording}],\n\
             \x20           games: &[{game}],\n\
             \x20           mappings: &[{mapping}],\n\
             \x20           depth_profiles: {depth},\n\
             \x20           camera_bindings: {camera},\n\
             \x20       }},\n",
            manifest = embed("catalog.json"),
            device = embed("device-profile.json"),
            recording = embed("recording-profile.json"),
            game = embed("game-profile.json"),
            mapping = embed("mapping.json"),
            depth = optional_payloads("depth-profile.json"),
            camera = optional_payloads("camera-binding.json"),
        ));
        game_ids.push(game_id.to_owned());
    }

    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is unset"));
    let header =
        "// @generated by build.rs from config/catalogs/shipped-games.json — do not edit.\n";
    std::fs::write(
        out_dir.join("embedded_dev_catalogs.rs"),
        format!(
            "{header}fn embedded_dev_catalogs() -> Vec<CatalogSources<'static>> {{\n    vec![\n{catalog_entries}    ]\n}}\n"
        ),
    )
    .expect("cannot write embedded_dev_catalogs.rs");
    std::fs::write(
        out_dir.join("embedded_dev_game_ids.rs"),
        format!(
            "{header}const EMBEDDED_DEV_GAME_IDS: &[&str] = &[\n{}];\n",
            game_ids
                .iter()
                .map(|id| format!("    \"{id}\",\n"))
                .collect::<String>()
        ),
    )
    .expect("cannot write embedded_dev_game_ids.rs");
}
